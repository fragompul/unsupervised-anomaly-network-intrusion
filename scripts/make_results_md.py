"""Render docs/benchmark_results.md from results/analysis/summary.json (no hand-typed numbers)."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
S = json.loads((ROOT / "results" / "analysis" / "summary.json").read_text())
T = S["titles"]
DS = {"nsl_kdd": "NSL-KDD", "unsw_nb15": "UNSW-NB15", "cicids2017": "CIC-IDS2017"}
ENS = {"ens_all": "Ensemble (all)", "ens_diverse": "Ensemble (diverse 5)"}


def title(d: str) -> str:
    if d in ENS:
        return ENS[d]
    base, _, rest = d.partition("+")
    return T.get(base, base) + (f" +{rest}" if rest else "")


def md_table(header: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "--:" for i in range(len(header))) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


lines = ["# Benchmark results (Noctua protocol)", "",
         "Generated by `scripts/make_results_md.py` from `results/analysis/summary.json`; every number below is",
         "recomputed from raw scores. See [protocol.md](protocol.md) for definitions.", ""]  # fmt: skip

main = S.get("main")
if main:
    lines += ["## E1 — main benchmark (ROC-AUC, mean ± std over seeds)", ""]
    for regime in ("clean", "natural"):
        cols = [d for d in DS if any(r["dataset"] == d and r["regime"] == regime for r in main["table"])]
        dets = sorted({r["detector"] for r in main["table"]}, key=lambda d: (d.startswith("ens_"), -np.mean([r["roc"] for r in main["table"] if r["detector"] == d and r["regime"] == regime] or [0])))  # fmt: skip
        rows = []
        for d in dets:
            cells = []
            for c in cols:
                r = next((r for r in main["table"] if r["detector"] == d and r["dataset"] == c and r["regime"] == regime), None)
                cells.append("—" if r is None else f"{r['roc']:.3f} ± {r['roc_std']:.3f}")
            rows.append([title(d), *cells])
        lines += [f"### {regime.capitalize()} training", "", md_table(["Detector", *[DS[c] for c in cols]], rows), ""]
    st = main["stats"].get("all_seeds")
    if st:
        lines += [f"Friedman χ² = {st['statistic']:.1f} over {st['n_blocks']} blocks (dataset × regime × seed), p = {st['p']:.2g}; "
                  f"Nemenyi CD = {st['cd']:.2f}. Best mean rank: **{title(main['stats']['best_by_rank'])}**.", ""]  # fmt: skip
    lines += ["### Calibration honesty (clean training, nominal α = 1%)", "",
              md_table(["Detector", *[f"{DS[c]} FPR" for c in DS if any(r['dataset'] == c for r in main['table'])]],
                       [[title(d), *[f"{100 * next((r['a1_fpr'] for r in main['table'] if r['detector'] == d and r['dataset'] == c and r['regime'] == 'clean'), float('nan')):.2f}%" for c in DS if any(r['dataset'] == c for r in main['table'])]]
                        for d in sorted({r['detector'] for r in main['table']})]), ""]  # fmt: skip

c = S.get("contamination")
if c:
    lines += ["## E2 — training contamination (ROC-AUC)", ""]
    for d in DS:
        rhos = sorted({r["rho"] for r in c["table"] if r["dataset"] == d})
        if not rhos:
            continue
        ids = [x for x in ("ae", "ae+ctr0.1", "knn", "knn+ctr0.1", "gmm", "gmm+ctr0.1", "flow", "flow+ctr0.1", "iforest")]
        rows = []
        for i in ids:
            vals = [next((r["roc"] for r in c["table"] if r["dataset"] == d and r["detector"] == i and abs(r["rho"] - rho) < 1e-9), None) for rho in rhos]
            rows.append([title(i), *["—" if v is None else f"{v:.3f}" for v in vals]])
        lines += [f"### {DS[d]}", "", md_table(["Detector", *[f"ρ={100 * r:g}%" for r in rhos]], rows), ""]
    gains = [g for g in c["ctr_gain"] if abs(g["rho"] - 0.05) < 1e-9 and g["detector"].endswith("+ctr0.1")]
    if gains:
        lines += [f"Mean CTR gain at ρ = 5% (trim 10%): **{100 * np.mean([g['gain'] for g in gains]):+.1f} AUC points** "
                  f"(positive in {sum(g['gain'] > 0 for g in gains)}/{len(gains)} dataset–detector pairs).", ""]  # fmt: skip

d = S.get("drift")
if d:
    days = ["Tue", "Wed", "Thu", "Fri"]
    dets = sorted({r["detector"] for r in d["table"]}, key=lambda x: np.mean([r["fpr_a1"] for r in d["table"] if r["detector"] == x]))
    rows = [[title(x), *[f"{100 * next((r['fpr_a1'] for r in d['table'] if r['detector'] == x and r['day'] == day), float('nan')):.1f}%" for day in days]] for x in dets]
    lines += ["## E3 — drift on CIC-IDS2017 (realized benign FPR, Monday-calibrated nominal 1%)", "", md_table(["Detector", *days], rows), ""]
    if d["psi_fpr_spearman"]:
        lines += [f"PSI of benign scores vs. realized FPR: Spearman ρ = {d['psi_fpr_spearman']['rho']:.2f} (p = {d['psi_fpr_spearman']['p']:.1e}).", ""]
    for a in d.get("drift_alarms", []):
        pr = "—" if a["precision"] is None else f"{100 * a['precision']:.0f}%"
        rc = "—" if a["recall"] is None else f"{100 * a['recall']:.0f}%"
        lines.append(f"* PSI ≥ {a['threshold_psi']}: precision {pr}, recall {rc} for detecting FPR ≥ 3× nominal.")
    lines.append("")

t = S.get("transfer")
if t:
    cfg = [("unsw_nb15", "unsw_nb15", "source"), ("unsw_nb15", "cicids2017", "source"), ("unsw_nb15", "cicids2017", "target"),
           ("cicids2017", "cicids2017", "source"), ("cicids2017", "unsw_nb15", "source"), ("cicids2017", "unsw_nb15", "target")]  # fmt: skip
    names = ["U→U", "U→C", "U→C dom-std", "C→C", "C→U", "C→U dom-std"]
    dets = sorted({r["detector"] for r in t["table"] if not r["detector"].startswith("ens_")}, key=lambda x: -np.mean([r["roc"] for r in t["table"] if r["detector"] == x]))
    rows = [[title(x), *[f"{next((r['roc'] for r in t['table'] if r['detector'] == x and (r['source'], r['target'], r['scaler']) == c), float('nan')):.3f}" for c in cfg]] for x in dets]
    lines += ["## E4 — dataset shift (harmonized 18-feature space, ROC-AUC)", "", md_table(["Detector", *names], rows), ""]

(ROOT / "docs" / "benchmark_results.md").write_text("\n".join(lines) + "\n")
print("wrote docs/benchmark_results.md")
